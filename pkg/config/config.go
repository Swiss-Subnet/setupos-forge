// Package config renders, parses and validates the config.ini that SetupOS
// reads from the CONFIG partition of its installer image.
//
// Every rule here mirrors dfinity/ic at b9f8bbf07a1aca5212ff30c7690c08d6ceeb9566:
//
//	rs/ic_os/config/tool/src/setupos/config_ini.rs   keys, types, prefix rules
//	rs/ic_os/config/tool/src/main.rs                 reward type, IPv4 grouping
//	ic-os/components/setupos/check-hardware.sh       reward type to generation
//	ic-os/components/setupos/check-network.sh        domain syntax
//
// SetupOS runs check-config.sh before it touches a disk, so everything this
// package reports is something you would otherwise discover at the rack.
package config

import (
	"fmt"
	"net/netip"
	"strings"
)

type Config struct {
	IPv6Prefix  string // leading hextets, no "::"
	IPv6Gateway netip.Addr

	IPv4 *IPv4 // nil for an IPv6-only node

	Domain                            string
	NodeRewardType                    string
	Verbose                           bool
	EnableTrustedExecutionEnvironment bool
}

// SetupOS drops the IPv4 block unless all three fields are present.
type IPv4 struct {
	Address      netip.Addr
	Gateway      netip.Addr
	PrefixLength int
}

// Comparing two config.ini files by line mostly shows the stock template's
// commentary, so compare by setting instead.
func (c Config) Settings() map[string]string {
	out := map[string]string{}
	set := func(k, v string) {
		if v != "" {
			out[k] = v
		}
	}

	set("ipv6_prefix", c.IPv6Prefix)
	if c.IPv6Gateway.IsValid() {
		set("ipv6_gateway", c.IPv6Gateway.String())
	}
	set("node_reward_type", c.NodeRewardType)
	set("domain", c.Domain)
	if c.IPv4 != nil {
		set("ipv4_address", c.IPv4.Address.String())
		set("ipv4_gateway", c.IPv4.Gateway.String())
		set("ipv4_prefix_length", fmt.Sprint(c.IPv4.PrefixLength))
	}
	if c.Verbose {
		set("verbose", "true")
	}
	if c.EnableTrustedExecutionEnvironment {
		set("enable_trusted_execution_environment", "true")
	}
	return out
}

// Render does not validate. Call Validate first.
func (c Config) Render() []byte {
	var b strings.Builder
	b.WriteString("# Generated by setupos-forge. Do not edit on the USB stick.\n\n")

	fmt.Fprintf(&b, "ipv6_prefix=%s\n", c.IPv6Prefix)
	fmt.Fprintf(&b, "ipv6_gateway=%s\n", c.IPv6Gateway)

	if c.NodeRewardType != "" {
		fmt.Fprintf(&b, "node_reward_type=%s\n", c.NodeRewardType)
	}
	if c.IPv4 != nil {
		fmt.Fprintf(&b, "ipv4_address=%s\n", c.IPv4.Address)
		fmt.Fprintf(&b, "ipv4_prefix_length=%d\n", c.IPv4.PrefixLength)
		fmt.Fprintf(&b, "ipv4_gateway=%s\n", c.IPv4.Gateway)
	}
	if c.Domain != "" {
		fmt.Fprintf(&b, "domain=%s\n", c.Domain)
	}
	if c.Verbose {
		b.WriteString("verbose=true\n")
	}
	if c.EnableTrustedExecutionEnvironment {
		b.WriteString("enable_trusted_execution_environment=true\n")
	}

	return []byte(b.String())
}
